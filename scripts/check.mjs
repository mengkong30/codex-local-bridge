import fs from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const parts=['runtime-api.js','runtime-reliability.js','runtime-layout.js','runtime-dsl.js','runtime-review.js','code-main.js'];
const generated='// Generated by build-runtime.mjs; edit the source modules.\n'+'const API_CONTRACT = '+JSON.stringify(JSON.parse(await fs.readFile(new URL('api-contract.json',root),'utf8')))+';\n'+(await Promise.all(parts.map(p=>fs.readFile(new URL('figma/'+p,root),'utf8')))).join('\n');
assert.equal(await fs.readFile(new URL('figma/code.js',root),'utf8'),generated,'Run npm run build before committing runtime changes');
let checked=0;
async function walk(url){for(const entry of await fs.readdir(url,{withFileTypes:true})){
 if(['.git','node_modules','output'].includes(entry.name))continue;
 const file=new URL(entry.name+(entry.isDirectory()?'/':''),url);
 if(entry.isDirectory()){await walk(file);continue;}
 if(/\.(mjs|cjs|js)$/.test(entry.name)){
  const result=spawnSync(process.execPath,['--check',fileURLToPath(file)],{stdio:'inherit',windowsHide:true});
  assert.equal(result.status,0,'Syntax check failed: '+file);checked++;
 }
 if(entry.name.endsWith('.json'))JSON.parse(await fs.readFile(file,'utf8'));
}}
await walk(root);
const portable=JSON.parse(await fs.readFile(new URL('plugin.json',root),'utf8'));
const legacy=JSON.parse(await fs.readFile(new URL('.codex-plugin/plugin.json',root),'utf8'));
const pkg=JSON.parse(await fs.readFile(new URL('package.json',root),'utf8'));
assert.equal(portable.version,pkg.version);assert.equal(legacy.version,pkg.version);
assert.equal((await fs.readFile(new URL('VERSION',root),'utf8')).trim(),pkg.version);
assert.equal(await fs.readFile(new URL('mcp.json',root),'utf8'),await fs.readFile(new URL('.mcp.json',root),'utf8'));
const contract=JSON.parse(await fs.readFile(new URL('api-contract.json',root),'utf8'));
assert.equal(new Set([...contract.reads,...contract.writes]).size,contract.reads.length+contract.writes.length);
assert.equal(new Set(contract.nodeProperties).size,contract.nodeProperties.length);
const designManifest=JSON.parse(await fs.readFile(new URL('figma/manifest.json',root),'utf8'));
const devManifest=JSON.parse(await fs.readFile(new URL('figma/manifest-dev.json',root),'utf8'));
assert.deepEqual(designManifest.editorType,['figma','figjam','slides']);
assert.deepEqual(devManifest.editorType,['dev']);assert.deepEqual(devManifest.capabilities,['inspect']);
assert.notEqual(designManifest.id,devManifest.id);assert.equal(designManifest.documentAccess,'dynamic-page');assert.ok(designManifest.permissions.includes('teamlibrary'));
console.log('PASS syntax, JSON, generated runtime, portable configuration and version consistency: '+checked+' JavaScript files');
